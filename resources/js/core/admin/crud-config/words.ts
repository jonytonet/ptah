const en = { ...langEn, ...extraEn };
const ptBR: typeof en = { ...langEn, ...langPtBR, ...extraPtBR };

export type CrudConfigWords = typeof en;

const dictionaries: Record<string, CrudConfigWords> = { en, pt: ptBR };

/** The words for a locale (`pt_BR`, `pt-BR`, `en`…); English when unknown. */
export function crudConfigWords(locale?: string | null): CrudConfigWords {
    const lang = (locale ?? (typeof document !== 'undefined' ? document.documentElement.lang : '') ?? '').toLowerCase().slice(0, 2);

    return dictionaries[lang] ?? en;
}

/** `:name` placeholders, as Laravel's trans() fills them. */
export const fill = (template: string, values: Record<string, string | number>): string => template.replace(/:(\w+)/g, (whole, name: string) => (name in values ? String(values[name]) : whole));
